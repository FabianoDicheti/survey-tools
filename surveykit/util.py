"""Small shared helpers: reporting, dates, and the generated-file banner."""
import datetime
import sys


def today():
    return datetime.date.today().isoformat()


def banner(cmd):
    return f"**Generated by `survey {cmd}`. Do not edit.**"


def warn(msg):
    print(f"⚠️  {msg}", file=sys.stderr)


class Report:
    """Collect PASS/WARN/FAIL lines for a command; exit code 1 on any FAIL."""

    def __init__(self):
        self.lines, self.fails, self.warns = [], 0, 0

    def ok(self, msg):
        self.lines.append(("PASS", msg))

    def warn(self, msg):
        self.warns += 1
        self.lines.append(("WARN", msg))

    def fail(self, msg):
        self.fails += 1
        self.lines.append(("FAIL", msg))

    def info(self, msg):
        self.lines.append(("    ", msg))

    def print(self):
        for k, m in self.lines:
            print(f"  {k}  {m}")

    @property
    def rc(self):
        return 1 if self.fails else 0
