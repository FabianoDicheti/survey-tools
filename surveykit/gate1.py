"""`survey gate1 sample|score` — does the taxonomy actually partition?

Run after indexing and BEFORE any web search or prose; re-run after every fetch
wave on the same deterministic sample design so runs compare. Each sampled row is
placed twice: by the indexer's `locus_proposed` (the seed), and by a blind agent
(`survey-blind-placer`) given only TAXONOMY.md and the row's one-line conclusion.

Three metrics, three separate verdicts (the original check collapsed them into
one and reported "does not partition" when only spread had failed):

    agreement  — below agree_fatal the cell definitions are ambiguous
    doubles    — above doubles_max the axis is not a partition
    spread     — a cell under spread_min is a corpus gap, not an axis defect
"""
import json
import random
import sys
from collections import Counter, defaultdict

from .schema import read_jsonl, read_tsv, write_json
from .util import today


def _paths(cfg):
    p = cfg.path("positioning_dir")
    return (p / "gate1_sample.md", p / ".gate1_seed.tsv", p / "TAXONOMY_TEST.md",
            p / "TAXONOMY_TEST.json", p / "gate1_history.jsonl")


def stratify(rows, n):
    """Proportional by source_cluster, evenly spaced through each stratum's sorted
    keys. Deterministic: the same corpus always yields the same sample."""
    strata = defaultdict(list)
    for r in rows:
        strata[r.get("source_cluster") or "-"].append(r)
    for v in strata.values():
        v.sort(key=lambda r: r["survey_key"])
    total = sum(len(v) for v in strata.values())
    quota = {k: max(1, round(n * len(v) / total)) for k, v in strata.items()}
    order = sorted(strata, key=lambda k: (-len(strata[k]), k))
    while sum(quota.values()) > n and any(quota[k] > 1 for k in order):
        for k in order:
            if quota[k] > 1 and sum(quota.values()) > n:
                quota[k] -= 1
    while sum(quota.values()) < min(n, total):
        for k in order:
            if quota[k] < len(strata[k]) and sum(quota.values()) < n:
                quota[k] += 1
    picked = []
    for k in sorted(strata):
        v, q = strata[k], min(quota[k], len(strata[k]))
        if q:
            step = len(v) / q
            picked += [v[int(i * step)] for i in range(q)]
    return picked[:n]


def sample(cfg, args):
    g = cfg.gate1
    rows = read_jsonl(cfg.corpus)
    if not rows:
        print("no corpus.jsonl — run `survey index build` first", file=sys.stderr)
        return 1
    # An unciteable document has no cell by construction; sampling it measures the
    # reader's patience, not the taxonomy.
    cit = [r for r in rows if r.get("citable")]
    s = stratify(cit, g["n"])
    random.Random(g["seed"]).shuffle(s)          # the order must not encode the cluster
    f_sample, f_seed, *_ = _paths(cfg)
    choices = " | ".join(cfg.all_locus_ids)
    lines = [
        "# GATE 1 — the blind worksheet", "", "**Generated by `survey gate1 sample`.**", "",
        "## Instructions to the placing agent", "",
        f"Read **only** `{cfg.layout['positioning_dir']}/TAXONOMY.md` and then this file. **Do not** open",
        "the corpus, the seed map, the ledger, any summary, or any sibling agent's output. You are the",
        "blind half of a two-way comparison and the comparison is void if you see the other half.", "",
        "For each row emit one tab-separated line `id<TAB>cell<TAB>double<TAB>reason`:", "",
        f"- `cell` ∈ `{choices}`",
        "- `double` is `yes` **only if two cells fit equally well** — not if it was merely hard.",
        "  Understating it defeats the purpose of this gate.",
        "- `reason` ≤ 20 words, naming **which decision** you classified.", "",
        f"Write your output to `{cfg.layout['positioning_dir']}/gate1_blind.tsv` and nothing else.", "",
        "---", "", "| id | one-line conclusion |", "|---|---|",
    ]
    for i, r in enumerate(s, 1):
        lines.append(f"| {i:02d} | {(r.get('one_line') or '').replace('|', chr(92) + '|')} |")
    f_sample.write_text("\n".join(lines) + "\n", encoding="utf-8")
    with f_seed.open("w", encoding="utf-8") as f:
        f.write("id\tsurvey_key\tsource_cluster\tseed_cell\tseed_reason\n")
        for i, r in enumerate(s, 1):
            f.write(f"{i:02d}\t{r['survey_key']}\t{r.get('source_cluster') or '-'}\t"
                    f"{r.get('locus_proposed') or '?'}\t{(r.get('locus_reason') or '')[:60]}\n")
    print(f"corpus {len(rows)} rows, {len(cit)} citable; sample {len(s)} -> {f_sample.name}")
    print(f"strata {dict(Counter(r.get('source_cluster') or '-' for r in s))}")
    print("Next: dispatch ONE survey-blind-placer with the worksheet and TAXONOMY.md only.")
    return 0


def _seed_cells(cfg, s):
    s = s[5:] if s.startswith("SEED:") else s
    return set(cfg.parse_locus(s))


def score(cfg, args):
    g = cfg.gate1
    f_sample, f_seed, f_md, f_json, f_hist = _paths(cfg)
    blindpath = args.blind or str(cfg.path("positioning_dir", "gate1_blind.tsv"))
    blind, malformed = {}, []
    for line in open(blindpath, encoding="utf-8").read().splitlines():
        if not line.strip() or line.startswith("#") or line.startswith("id\t"):
            continue
        p = [x.strip() for x in line.split("\t")]
        if len(p) < 3 or p[1] not in cfg.all_locus_ids:
            malformed.append(line)
            continue
        blind[p[0].zfill(2)] = {"cell": p[1], "double": p[2].lower().startswith("y"),
                                "reason": p[3] if len(p) > 3 else ""}
    seed = {r["id"]: r for r in read_tsv(f_seed)}
    ids = sorted(set(seed) & set(blind))
    missing = sorted(set(seed) - set(blind))
    agree = [i for i in ids if blind[i]["cell"] in _seed_cells(cfg, seed[i]["seed_cell"])]
    doubles = [i for i in ids if blind[i]["double"]]
    spread = Counter(blind[i]["cell"] for i in ids)
    n = len(ids) or 1
    a, d = len(agree) / n, len(doubles) / n
    thin = [c for c in cfg.cell_ids if spread.get(c, 0) < g["spread_min"]]
    v = {
        "date": today(), "n": len(ids), "missing": missing, "malformed": malformed,
        "agreement": {"value": round(a, 4), "count": len(agree),
                      "verdict": "PASS" if a >= g["agree_pass"] else ("FATAL" if a < g["agree_fatal"] else "WARN")},
        "doubles": {"value": round(d, 4), "count": len(doubles),
                    "verdict": "PASS" if d <= g["doubles_max"] else "FAIL"},
        "spread": {"counts": dict(spread), "thin": thin, "verdict": "PASS" if not thin else "WARN"},
        "thresholds": g,
    }
    # Partition verdict = agreement + doubles. Thinness is reported separately: it
    # is a corpus gap for survey-gaps, never evidence the axis fails.
    partition = "PASS" if v["agreement"]["verdict"] != "FATAL" and v["doubles"]["verdict"] == "PASS" else "FAIL"
    v["partition"] = partition
    v["overall"] = "PASS" if partition == "PASS" and not thin and v["agreement"]["verdict"] == "PASS" else \
        ("FAIL" if partition == "FAIL" else "PASS_WITH_WARNINGS")
    write_json(f_json, v)
    with f_hist.open("a", encoding="utf-8") as f:
        f.write(json.dumps({k: v[k] for k in ("date", "n", "partition", "overall")} |
                           {"agreement": v["agreement"]["value"], "doubles": v["doubles"]["value"],
                            "thin": thin, "corpus": len(read_jsonl(cfg.corpus))}) + "\n")

    pct = lambda x: f"{round(100 * x)}%"
    out = [f"# TAXONOMY_TEST — GATE 1", "", f"**Run {today()}.** Generated by `survey gate1 score`; "
           "machine copy in `TAXONOMY_TEST.json`, history in `gate1_history.jsonl`.", "",
           f"## Partition: **{partition}** · overall: **{v['overall']}**", "",
           "| metric | value | threshold | verdict |", "|---|---|---|---|",
           f"| agreement | **{pct(a)}** ({len(agree)}/{len(ids)}) | ≥{pct(g['agree_pass'])}, fatal <{pct(g['agree_fatal'])} | {v['agreement']['verdict']} |",
           f"| doubles | **{len(doubles)}/{len(ids)} = {pct(d)}** | ≤{pct(g['doubles_max'])} | {v['doubles']['verdict']} |",
           f"| thin cells (<{g['spread_min']}) | **{', '.join(thin) or 'none'}** | none | {v['spread']['verdict']} |",
           "", "## Spread", "", "| cell | n |", "|---|---|"]
    out += [f"| {c} | {spread.get(c, 0)} |" for c in cfg.all_locus_ids]
    out += ["", "## Disagreements", "", "A disagreement is not automatically the reader being right; the seed "
            "map lists the cases where the seed is known wrong.", "",
            "| id | key | cluster | seed | blind | double | reason |", "|---|---|---|---|---|---|---|"]
    for i in ids:
        if i not in agree:
            out.append(f"| {i} | `{seed[i]['survey_key']}` | {seed[i]['source_cluster']} | {seed[i]['seed_cell']} | "
                       f"{blind[i]['cell']} | {'**yes**' if blind[i]['double'] else 'no'} | {blind[i]['reason']} |")
    if doubles:
        out += ["", "## Doubles", "", "| id | key | blind | reason |", "|---|---|---|---|"]
        out += [f"| {i} | `{seed[i]['survey_key']}` | {blind[i]['cell']} | {blind[i]['reason']} |" for i in doubles]
    out += ["", "## What this verdict means", ""]
    if v["agreement"]["verdict"] == "FATAL":
        out.append("🛑 Agreement below the fatal floor: the cell definitions are ambiguous. Rewrite the axes "
                   "and cell tests before anything else.")
    if v["doubles"]["verdict"] == "FAIL":
        out.append(f"🛑 Doubles above {pct(g['doubles_max'])}: the axis is not a partition. Remedies — sharpen the "
                   f"axes, add an axis, or promote the crosscut — are {cfg.owner}'s decision, now, not after drafting.")
    if thin:
        out.append(f"⚠️ Thin cells {', '.join(thin)}: a corpus gap for `survey-gaps` (or a cell that is not a real "
                   "research area — GATE 2 decides which). Not an axis defect.")
    if partition == "PASS":
        out.append("The taxonomy partitions. Re-run after every fetch wave; a taxonomy that passes on the inherited "
                   "corpus and fails on the fetched one is telling you the fetch changed the subject. Boundary rules "
                   "added after this run must be re-scored.")
    if missing:
        out.append(f"⚠️ {len(missing)} sampled rows got no blind placement: {', '.join(missing)}")
    if malformed:
        out.append(f"⚠️ {len(malformed)} malformed blind lines ignored.")
    f_md.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"agreement {pct(a)} [{v['agreement']['verdict']}]  doubles {pct(d)} [{v['doubles']['verdict']}]  "
          f"thin {thin or 'none'}\npartition {partition}  overall {v['overall']}  -> {f_md.name}")
    return 0 if partition == "PASS" else 1
